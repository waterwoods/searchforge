#!/usr/bin/env python3
"""
job_interview_coach.py - LLM-powered interview coaching for a specific job
==========================================================================

This script generates personalized interview coaching advice for a specific job
from a scored jobs JSON file.

Usage:
    python -m experiments.jobhunter.job_interview_coach --job-id <job_id> [--scored-file <path>] [--profile-file <path>] [--output-dir <dir>]
"""

import sys
import json
import argparse
import logging
from pathlib import Path
from datetime import datetime
from typing import Dict, List, Optional

# Add project root to path
project_root = Path(__file__).parent.parent.parent
sys.path.insert(0, str(project_root))

from pydantic import BaseModel, Field
from services.fiqa_api.clients import get_openai_client

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger(__name__)

# Default model for coaching
DEFAULT_LLM_MODEL = "gpt-4o-mini"

# Maximum description length to send to LLM
MAX_DESC_CHARS = 4000


class JobCoachAdvice(BaseModel):
    """Coaching advice generated by LLM for a specific job interview."""
    
    fit_summary: str = Field(..., description="Brief summary of how the candidate fits this role (1-2 paragraphs)")
    pitch_bullets: List[str] = Field(..., description="4-6 bullet points on how to talk about experience")
    risk_notes: Optional[str] = Field(None, description="Optional notes on risks or weak spots to address")
    questions_to_ask: List[str] = Field(..., description="3-5 good questions to ask the interviewer")


def find_latest_scored_file() -> Optional[Path]:
    """
    Find the latest scored jobs JSON file in data/jobhunter/scored/.
    
    Returns:
        Path to the latest file, or None if none found.
    """
    scored_dir = project_root / "data" / "jobhunter" / "scored"
    if not scored_dir.exists():
        return None
    
    # Find all jobs_scored_*.json files
    scored_files = list(scored_dir.glob("jobs_scored_*.json"))
    if not scored_files:
        return None
    
    # Sort by modification time, return most recent
    scored_files.sort(key=lambda p: p.stat().st_mtime, reverse=True)
    return scored_files[0]


def load_scored_jobs(path: Path) -> List[Dict]:
    """
    Load scored jobs from JSON file.
    
    Args:
        path: Path to scored jobs JSON file
        
    Returns:
        List of job dictionaries with 'job' and 'score' keys
        
    Raises:
        FileNotFoundError: If file doesn't exist
        ValueError: If file contains invalid data
    """
    if not path.exists():
        raise FileNotFoundError(f"Scored jobs file not found: {path}")
    
    logger.info(f"Loading scored jobs from {path}")
    
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    
    if not isinstance(data, list):
        raise ValueError(f"Expected a list of scored jobs, got {type(data)}")
    
    logger.info(f"Loaded {len(data)} scored jobs")
    return data


def find_job_by_id(scored_jobs: List[Dict], job_id: str) -> Optional[Dict]:
    """
    Find a job by job_id in the scored jobs list.
    
    Args:
        scored_jobs: List of job dictionaries
        job_id: Job ID to search for
        
    Returns:
        Job dictionary with 'job' and 'score' keys, or None if not found
    """
    for item in scored_jobs:
        if isinstance(item, dict) and "job" in item:
            job = item["job"]
            if isinstance(job, dict) and job.get("job_id") == job_id:
                return item
    return None


def get_profile_summary_interactive() -> str:
    """
    Get profile summary from user via interactive input.
    
    Returns:
        Profile summary string
    """
    print("\n" + "=" * 60)
    print("Profile Summary")
    print("=" * 60)
    print("Please provide a brief summary of your background and experience.")
    print("This will help generate personalized interview coaching.")
    print("(Press Enter on an empty line to finish)\n")
    
    lines = []
    while True:
        try:
            line = input()
            if not line.strip() and lines:
                # Empty line after some content means done
                break
            if line.strip():
                lines.append(line)
        except EOFError:
            break
    
    return "\n".join(lines).strip()


def load_profile_from_file(path: Path) -> str:
    """
    Load profile summary from a markdown file.
    
    Args:
        path: Path to profile markdown file
        
    Returns:
        Profile summary string
        
    Raises:
        FileNotFoundError: If file doesn't exist
    """
    if not path.exists():
        raise FileNotFoundError(f"Profile file not found: {path}")
    
    with open(path, "r", encoding="utf-8") as f:
        return f.read().strip()


def truncate_description(description: str, max_length: int = MAX_DESC_CHARS) -> str:
    """
    Truncate job description to avoid token limits.
    
    Args:
        description: Full job description
        max_length: Maximum length in characters
        
    Returns:
        Truncated description with ellipsis if needed
    """
    if not description:
        return ""
    
    if len(description) <= max_length:
        return description
    
    return description[:max_length] + "\n\n...[truncated]..."


def generate_job_coaching_advice(
    job: Dict,
    score: Dict,
    profile_summary: str,
    model: str = DEFAULT_LLM_MODEL,
) -> JobCoachAdvice:
    """
    Generate interview coaching advice using LLM.
    
    Args:
        job: Job dictionary (JobPosting fields)
        score: Score dictionary (JobScore fields)
        profile_summary: Candidate profile summary
        model: LLM model to use
        
    Returns:
        JobCoachAdvice instance
        
    Raises:
        ValueError: If LLM call fails or response is invalid
    """
    client = get_openai_client()
    if client is None:
        raise ValueError("OpenAI client not available. Please set OPENAI_API_KEY environment variable.")
    
    # System prompt
    system_prompt = """You are a job interview coach for a senior LLM/infrastructure/data engineer.

The candidate has:
- Strong Python, data/ML infrastructure, and cloud (GCP) experience
- Recent experience building production LLM/RAG/agent systems with LangGraph, evaluation, observability, and coding agents
- Expertise in: Python, backend, data engineering, cloud (GCP), RAG, LangGraph/agentic systems, observability, evaluation, coding agents

Your role is to provide concise, practical, and concrete interview coaching advice. Focus on:
1. A brief fit summary (1-2 paragraphs) explaining how the candidate's experience aligns with the role
2. 4-6 specific bullet points on how to talk about their experience (be concrete and actionable)
3. Optional risk notes on weak spots or gaps to address
4. 3-5 thoughtful questions to ask the interviewer that demonstrate interest and understanding

Be practical, specific, and focused on helping the candidate succeed in the interview."""

    # Build user prompt
    job_title = job.get("title", "Unknown")
    company = job.get("company", "Unknown")
    location = job.get("location", "Not specified")
    description = truncate_description(job.get("description", ""))
    
    match_score = score.get("match_score", "N/A")
    category = score.get("category", "N/A")
    reasons = score.get("reasons", "")
    talk_track = score.get("talk_track", "")
    
    user_prompt = f"""Generate interview coaching advice for this job:

Job Title: {job_title}
Company: {company}
Location: {location}
Match Score: {match_score}/10
Category: {category}
Match Reasons: {reasons}
Talk Track: {talk_track}

Job Description:
{description}

Candidate Profile Summary:
{profile_summary}

Please provide coaching advice in JSON format with these exact fields:
- fit_summary: Brief summary (1-2 paragraphs) of how the candidate fits this role
- pitch_bullets: List of 4-6 bullet points (strings) on how to talk about experience - be specific and actionable
- risk_notes: Optional string with notes on risks or weak spots to address (can be null if none)
- questions_to_ask: List of 3-5 questions (strings) to ask the interviewer"""

    try:
        response = client.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            response_format={"type": "json_object"},
            temperature=0.3,
            timeout=60.0,
        )
        
        content = response.choices[0].message.content
        if not content:
            raise ValueError("Empty response from LLM")
        
        # Parse and validate
        data = json.loads(content)
        advice = JobCoachAdvice.model_validate(data)
        
        return advice
        
    except json.JSONDecodeError as e:
        logger.error(f"Failed to parse LLM response as JSON: {e}")
        logger.debug(f"Raw response: {content[:500] if 'content' in locals() else 'N/A'}")
        raise ValueError(f"LLM response is not valid JSON: {e}")
    
    except Exception as e:
        logger.error(f"Failed to generate coaching advice: {e}")
        raise ValueError(f"LLM call failed: {e}")


def format_output(advice: JobCoachAdvice, job: Dict, score: Dict) -> str:
    """
    Format coaching advice for terminal display.
    
    Args:
        advice: JobCoachAdvice instance
        job: Job dictionary
        score: Score dictionary
        
    Returns:
        Formatted string for terminal output
    """
    job_title = job.get("title", "Unknown")
    company = job.get("company", "Unknown")
    
    lines = [
        f"\n{'=' * 70}",
        f"Job Interview Coaching for {job_title} @ {company}",
        f"{'=' * 70}\n",
        "Fit Summary:",
        "-" * 70,
        advice.fit_summary,
        "\n",
        "How to talk about your experience:",
        "-" * 70,
    ]
    
    for bullet in advice.pitch_bullets:
        lines.append(f"  • {bullet}")
    
    if advice.risk_notes:
        lines.extend([
            "\n",
            "Risks / Weak spots:",
            "-" * 70,
            advice.risk_notes,
        ])
    
    lines.extend([
        "\n",
        "Questions to ask the interviewer:",
        "-" * 70,
    ])
    
    for question in advice.questions_to_ask:
        lines.append(f"  • {question}")
    
    lines.append("\n" + "=" * 70 + "\n")
    
    return "\n".join(lines)


def save_markdown_report(
    advice: JobCoachAdvice,
    job: Dict,
    score: Dict,
    output_dir: Path,
    job_id: str,
) -> Path:
    """
    Save coaching advice to a Markdown file.
    
    Args:
        advice: JobCoachAdvice instance
        job: Job dictionary
        score: Score dictionary
        output_dir: Output directory
        job_id: Job ID for filename
        
    Returns:
        Path to saved markdown file
    """
    output_dir.mkdir(parents=True, exist_ok=True)
    
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    filename = f"job_coach_{job_id}.md"
    output_path = output_dir / filename
    
    job_title = job.get("title", "Unknown")
    company = job.get("company", "Unknown")
    location = job.get("location", "Not specified")
    match_score = score.get("match_score", "N/A")
    category = score.get("category", "N/A")
    url = job.get("url", "")
    
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(f"# Job Interview Coaching\n\n")
        f.write(f"**Job:** {job_title}\n\n")
        f.write(f"**Company:** {company}\n\n")
        f.write(f"**Location:** {location}\n\n")
        f.write(f"**Match Score:** {match_score}/10 (Category: {category})\n\n")
        if url:
            f.write(f"**URL:** {url}\n\n")
        f.write(f"**Generated:** {timestamp}\n\n")
        f.write("---\n\n")
        
        f.write("## Fit Summary\n\n")
        f.write(f"{advice.fit_summary}\n\n")
        
        f.write("## How to Talk About Your Experience\n\n")
        for bullet in advice.pitch_bullets:
            f.write(f"- {bullet}\n")
        f.write("\n")
        
        if advice.risk_notes:
            f.write("## Risks / Weak Spots\n\n")
            f.write(f"{advice.risk_notes}\n\n")
        
        f.write("## Questions to Ask the Interviewer\n\n")
        for question in advice.questions_to_ask:
            f.write(f"- {question}\n")
        f.write("\n")
    
    logger.info(f"Saved coaching report to {output_path}")
    return output_path


def main():
    """Main CLI entry point."""
    parser = argparse.ArgumentParser(
        description="Generate interview coaching advice for a specific job",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    
    parser.add_argument(
        "--scored-file",
        type=Path,
        default=None,
        help="Path to scored jobs JSON file (default: latest in data/jobhunter/scored/)",
    )
    
    parser.add_argument(
        "--job-id",
        type=str,
        required=True,
        help="Job ID to generate coaching for",
    )
    
    parser.add_argument(
        "--profile-file",
        type=Path,
        default=None,
        help="Path to profile summary markdown file (default: interactive input)",
    )
    
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=None,
        help="Output directory for markdown report (default: reports/jobhunter/)",
    )
    
    parser.add_argument(
        "--model",
        type=str,
        default=DEFAULT_LLM_MODEL,
        help=f"LLM model to use (default: {DEFAULT_LLM_MODEL})",
    )
    
    args = parser.parse_args()
    
    # Resolve default paths
    if args.scored_file is None:
        args.scored_file = find_latest_scored_file()
        if args.scored_file is None:
            print("Error: No scored jobs file found. Please specify --scored-file")
            sys.exit(1)
        print(f"Using latest scored file: {args.scored_file}")
    
    if args.output_dir is None:
        args.output_dir = project_root / "reports" / "jobhunter"
    
    # Load scored jobs
    try:
        scored_jobs = load_scored_jobs(args.scored_file)
    except Exception as e:
        print(f"Error loading scored jobs: {e}")
        sys.exit(1)
    
    # Find job by ID
    job_data = find_job_by_id(scored_jobs, args.job_id)
    if job_data is None:
        print(f"Error: Job with ID '{args.job_id}' not found in scored jobs file")
        sys.exit(1)
    
    job = job_data["job"]
    score = job_data.get("score", {})
    
    # Display job summary
    print("\n" + "=" * 70)
    print("Job Summary")
    print("=" * 70)
    print(f"Title: {job.get('title', 'Unknown')}")
    print(f"Company: {job.get('company', 'Unknown')}")
    print(f"Location: {job.get('location', 'Not specified')}")
    print(f"Match Score: {score.get('match_score', 'N/A')}/10")
    print(f"Category: {score.get('category', 'N/A')}")
    if job.get('url'):
        print(f"URL: {job.get('url')}")
    print("=" * 70)
    
    # Get profile summary
    if args.profile_file:
        try:
            profile_summary = load_profile_from_file(args.profile_file)
        except Exception as e:
            print(f"Error loading profile file: {e}")
            sys.exit(1)
    else:
        profile_summary = get_profile_summary_interactive()
        if not profile_summary:
            print("Error: Profile summary is required")
            sys.exit(1)
    
    # Generate coaching advice
    print("\nGenerating interview coaching advice...")
    try:
        advice = generate_job_coaching_advice(
            job=job,
            score=score,
            profile_summary=profile_summary,
            model=args.model,
        )
    except Exception as e:
        print(f"Error generating coaching advice: {e}")
        sys.exit(1)
    
    # Display output
    output_text = format_output(advice, job, score)
    print(output_text)
    
    # Save markdown report
    try:
        report_path = save_markdown_report(
            advice=advice,
            job=job,
            score=score,
            output_dir=args.output_dir,
            job_id=args.job_id,
        )
        print(f"Report saved to: {report_path}")
    except Exception as e:
        print(f"Warning: Failed to save report: {e}")
        logger.warning(f"Failed to save report: {e}")


if __name__ == "__main__":
    main()
